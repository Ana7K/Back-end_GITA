// Promise.race() აბრუნებს პირველი დასრულებული Promise-ის შედეგს ან resolveს ან rejectს
// Promise.any() აბრუნებს პირველივე წარმატებით შესრულებულ Promise-ს, თუნდაც სხვები წარუმატებელი იყოს. მხოლოდ მაშინ reject-დება როცა ყველა Promise წარუმატებელი იქნება

