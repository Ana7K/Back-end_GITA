// filter() - ფილტრავს, არჩევს მხოლოდ იმ ელემენტებს, რომლებიც აკმაყოფილებენ ჩვენ მიერ მითითებულ პირობას
// reduce() - მასივის ყველა ელემენტს ერთად აერთიანებს და ერთ საბოლოო მნიშვნელობად აბრუნებს

// 8)რა არის Promise?
// Promise არის მიკროტასკი, რომელიც არის მეორე დონე და ჯავასკრიპტის ასინქრონულ ოპერაციებს ჰენდლავს
